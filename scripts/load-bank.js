"use strict";

const fs = require("node:fs");
const path = require("node:path");
require("../blueprint.js");
require("../question-schema.js");

const ROOT = path.resolve(__dirname, "..");
const { exam } = globalThis.CCARP_BLUEPRINT;

function readArrays(directory) {
  return fs.readdirSync(path.join(ROOT, directory)).filter((name) => name.endsWith(".json")).sort().flatMap((name) => {
    const value = JSON.parse(fs.readFileSync(path.join(ROOT, directory, name), "utf8"));
    if (!Array.isArray(value)) throw new Error(`${directory}/${name} must contain an array.`);
    return value;
  });
}

function loadSources() {
  const records = readArrays("data/sources");
  const sources = new Map();
  for (const source of records) {
    if (!source.id || sources.has(source.id)) throw new Error(`Missing or duplicate source ID: ${source.id}`);
    if (!Array.isArray(source.evidence) || !source.evidence.length) throw new Error(`${source.id} has no research evidence.`);
    sources.set(source.id, source);
  }
  return sources;
}

function publicSource(source) {
  const { id, name, url, section, accessedAt, version } = source;
  return { id, name, url, section, accessedAt, version };
}

function loadBank() {
  const sources = loadSources();
  return readArrays("data/questions").map((record) => {
    const { sourceIds, ...question } = record;
    if (!Array.isArray(sourceIds) || !sourceIds.length || new Set(sourceIds).size !== sourceIds.length) {
      throw new Error(`${record.id} requires distinct sourceIds.`);
    }
    const resolved = sourceIds.map((id) => {
      if (!sources.has(id)) throw new Error(`${record.id} references unknown source ${id}.`);
      return publicSource(sources.get(id));
    });
    return { ...question, source: resolved[0], references: [...resolved.slice(1), {
      name: "Official CCAR-P Exam Guide", url: exam.url,
      section: `Domain ${question.domain}, objective ${question.objectiveId} (project-assigned ID)`,
      accessedAt: exam.verifiedAt, version: `${exam.version}, effective ${exam.effective}`
    }] };
  });
}

function validateBank(questions = loadBank()) {
  const errors = globalThis.CCARP_SCHEMA.validateQuestionBank(questions);
  if (errors.length) throw new Error(`Question bank validation failed:\n${errors.join("\n")}`);
  return questions;
}

function browserBank(questions) {
  return `// Generated by scripts/build.js. Edit data/questions and data/sources instead.\n` +
    `globalThis.CCARP_QUESTIONS = ${JSON.stringify(questions, null, 2)};\n`;
}

module.exports = { ROOT, loadBank, loadSources, validateBank, browserBank };
